"""Source -> typed roles -> 7+1/file supply, including adversarial variations."""
import unittest
from source_constraints import analyze_source
from admin_compute import compute

def project(text):return analyze_source(text)['projection']
def actions(text):return project(text)['contract']['actions']
def roles(frame):return {r['name']:r['value'] for r in frame['roles']}

class SemanticContractTests(unittest.TestCase):
    def test_shared_chinese_english_roles(self):
        for text in ['由 Analyst 读取 orders.csv 并生成 summary.json。',
                     'Analyst reads orders.csv and generates summary.json.']:
            r=project(text);a=r['contract']['actions']
            self.assertEqual([x['operation'] for x in a],['read','create'])
            self.assertEqual(roles(a[0]),{'executor':'Analyst','input':'orders.csv'})
            self.assertEqual(roles(a[1]),{'executor':'Analyst','artifact':'summary.json'})
            self.assertEqual([f['name'] for f in r['fileInputs']],['orders.csv'])
            self.assertEqual([f['name'] for f in r['fileOutputs']],['summary.json'])
            self.assertTrue(all(x.get('kind') for k in r['fields'].values() for x in k))

    def test_bilingual_recipient_before_after(self):
        for text in ['由 Sender 向 Reviewer 发送 report.csv。',
                     'Sender sends report.csv to Reviewer.',
                     '向 Reviewer 发送 report.csv。','Send report.csv to Reviewer.']:
            a=actions(text);self.assertEqual(len(a),1,text)
            self.assertEqual(roles(a[0])['recipient'],'Reviewer')
            self.assertEqual(roles(a[0])['payload'],'report.csv')
            self.assertFalse(project(text)['fileOutputs']) # sending is not creating
        for text in ['由 Reviewer 向 Sender 发送 report.csv。','Reviewer sends report.csv to Sender.']:
            self.assertEqual(roles(actions(text)[0])['executor'],'Reviewer')
            self.assertEqual(roles(actions(text)[0])['recipient'],'Sender')

    def test_read_relative_clause_never_produces(self):
        for text in ['读取初筛生成的结构化文件 `violation_clean.json`。',
                     'Read the file `violation_clean.json` generated by screening.']:
            r=project(text)
            self.assertEqual([f['name'] for f in r['fileInputs']],['violation_clean.json'])
            self.assertFalse(r['fileOutputs']);self.assertFalse(r['fields']['O'])

    def test_printed_name_is_not_a_generated_file(self):
        for text in ['打印 orders.csv。','Print orders.csv.']:
            r=project(text)
            self.assertEqual(r['contract']['actions'][0]['operation'],'emit')
            self.assertFalse(r['fileOutputs']);self.assertTrue(r['fields']['O'])
        r=compute('## WP1\nPrint orders.csv.\n## WP2\nRead orders.csv.')
        self.assertEqual(r['pipeline']['handover']['findings'][0]['code'],'io_handover_deficit')

    def test_negation_not_an_output_or_action_promise(self):
        for text in ['禁止生成 ledger.json。','不得读取 prod.csv。','无需生成 ledger.json。',
                     'Must not create ledger.json.','Do not read prod.csv.','Need not create ledger.json.']:
            r=project(text)
            self.assertFalse(r['fileOutputs']);self.assertFalse(r['fields']['O'])
            self.assertFalse(r['contract']['actions'])
        for text in ['无需生成 ledger.json 并发送 notice.txt。','Need not create ledger.json and send notice.txt.']:
            self.assertFalse(project(text)['fields']['O'])

    def test_from_role_and_alternative_assets_are_not_fake_outputs(self):
        r=project('Analyst creates report.json from orders.csv.')
        self.assertEqual([x['name'] for x in r['fileOutputs']],['report.json'])
        self.assertEqual([x['name'] for x in r['fileInputs']],['orders.csv'])
        for text in ['生成 a.csv 或 b.csv。','Create a.csv or b.csv.','读取 a.csv 或 b.csv。','Read a.csv or b.csv.',
                     '生成包含 orders.csv 内容的 report.json。']:
            r=project(text)
            self.assertFalse(r['fileOutputs']);self.assertFalse(r['fileInputs'])
            self.assertTrue(r['contract']['uncovered'])

    def test_modality_and_guard_scope_across_action_coordination(self):
        r=actions('Analyst must read orders.csv and create report.json.')
        self.assertEqual([a['modality'] for a in r],['REQUIRE','REQUIRE'])
        r=actions('当审核通过时生成 first.csv 并输出 second.json。')
        self.assertTrue(all(a['guard_sources'] for a in r))

    def test_condition_propagates_to_coordinated_outputs(self):
        for text in ['若审核通过，则生成 approved.csv 并发送 notice.txt。',
                     'If review succeeds, then generate approved.csv and send notice.txt.']:
            r=project(text);self.assertEqual(len(r['contract']['actions']),2)
            self.assertTrue(all(a['guard_sources'] for a in r['contract']['actions']))
            self.assertFalse(r['fileOutputs']);self.assertEqual(len(r['conditionalFileOutputs']),1)
            self.assertTrue(all('Condition:' in x['text']['en'] for x in r['fields']['O']))
        r=project('若审核通过，则生成 approved.csv；生成 unconditional.json。')
        self.assertEqual([x['name'] for x in r['fileOutputs']],['unconditional.json'])

    def test_approval_actor_not_executor(self):
        for text in ['未经风控经理 Risk_Manager 签字前，严禁对任何车辆解除锁定。',
                     'Without Risk_Manager approval, do not delete archived.csv.']:
            r=project(text)
            self.assertTrue(any(x['kind']=='approval_actor' for x in r['fields']['P']))
            self.assertFalse(any(x['kind']=='executor' for x in r['fields']['P']))
            self.assertTrue(r['fields']['B'])
        for text in ['经 CFO 授权后生成 refund.csv。','With CFO approval generate refund.csv.',
                     '必须经由 CFO 审批后方可生成 refund.csv。']:
            r=project(text)
            self.assertTrue(any(x['kind']=='approval_actor' and 'CFO' in x['text']['en'] for x in r['fields']['P']))
            self.assertFalse(any(x['kind']=='executor' for x in r['fields']['P']))
            self.assertFalse(r['fileOutputs']);self.assertTrue(r['conditionalFileOutputs'])

    def test_guarded_file_is_not_unconditional_wp_supply(self):
        for text in ['## WP1 准备\n若批准，则生成 data.json。\n## WP2 执行\n读取 data.json。',
                     '## WP1 Prepare\nIf approved, generate data.json.\n## WP2 Execute\nRead data.json.']:
            r=compute(text);io=r['pipeline']['handover']
            self.assertTrue(any(x['code']=='io_conditional_supply' for x in io['findings']))
            self.assertFalse(any(x['code']=='io_handover_deficit' for x in io['findings']))
            self.assertFalse(io['calculations'][0]['dependencyVerified'])

    def test_completion_does_not_invent_success_record(self):
        for text in ['生成 audit.log 即为完成。','Generate audit.log for task completion.']:
            r=project(text);self.assertEqual(len(r['fileOutputs']),1)
            self.assertTrue(r['fields']['C']);self.assertIn('audit.log',r['fields']['O'][0]['text']['en'])

    def test_unknown_argument_guard_is_not_silently_dropped(self):
        for text in ['生成 report.csv，除非数据为空。','Generate report.csv unless data is empty.',
                     '生成 report.csv 但仅在授权后执行。']:
            r=project(text)
            self.assertFalse(r['fileOutputs'],text)
            self.assertTrue(r['contract']['uncovered'] or r['conditionalFileOutputs'],text)

    def test_role_context_not_arbitrary_english_subject(self):
        for text in ['According to policy create report.csv.','After approval create report.csv.']:
            r=project(text)
            self.assertFalse(any(x['kind']=='executor' for x in r['fields']['P']))
            self.assertFalse(r['fileOutputs'])

    def test_dynamic_names_and_no_mutable_shared_state(self):
        a=project('由 Op_21 读取 alpha.csv 并生成 beta.json。')
        b=project('由 Op_93 读取 gamma.csv 并生成 delta.json。')
        self.assertEqual(roles(a['contract']['actions'][0])['executor'],'Op_21')
        self.assertEqual(roles(b['contract']['actions'][0])['executor'],'Op_93')
        self.assertEqual(a,project('由 Op_21 读取 alpha.csv 并生成 beta.json。'))

    def test_utf16_sources_and_json_immutability_boundary(self):
        text='😀 由数据员读取 `新档案.csv` 并生成 audit.json。'
        r=project(text)
        def walk(x):
            if isinstance(x,list):
                for y in x:walk(y)
            elif isinstance(x,dict):
                if {'quote','start','end'}<=x.keys():
                    self.assertEqual(text.encode('utf-16-le')[x['start']*2:x['end']*2].decode('utf-16-le'),x['quote'])
                for y in x.values():walk(y)
        walk(r)

if __name__=='__main__':unittest.main()
